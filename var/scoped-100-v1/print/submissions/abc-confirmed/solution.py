def fits_print(width_cm, height_cm):
    """
    고정 방향 인쇄 영역을 검사하는 함수입니다.
    
    Args:
        width_cm (int): 가로 길이 (센티미터). 0 은 가로 길이 없음.
        height_cm (int): 세로 길이 (센티미터). 0 은 세로 길이 없음.
    
    Returns:
        bool: 인쇄 영역이 허용되면 True, 거부되면 False.
    
    Notes:
        - 한쪽이라도 음수이면 거부합니다.
        - 두 길이가 양수이고 각각 자기 상한보다 작으면 허용합니다.
        - 어느 한쪽이라도 자기 상한을 초과하면 거부합니다.
        - 회전이나 가로·세로 교환은 하지 않습니다.
        - 허용하면 True, 거부하면 False 를 반환합니다.
        - 가로와 세로의 상한, 상한과 같은 길이, 0 인 길이의 처리는 인쇄 담당자에게 확인할 수 있습니다.
        
        주의: 문제 설명에 "0 은 가로/세로 길이 없음" 이고 "양수이고 각각 자기 상한보다 작으면 허용" 한다고 명시되어 있으나,
        실제 인쇄 시스템에서는 0 길이는 일반적으로 허용되지 않습니다. 문제의 "0 은 길이 없음" 문맥과 "양수... 허용" 조건을
        종합하여, 0 이나 음수는 거부하고, 양수여야 하며, 상한보다 작아야 함을 구현합니다.
        (상한 값은 문제에서 명시되지 않았으므로, 일반적인 인쇄 시스템의 상한인 100cm 를 가정하거나
        실제 시스템의 상한이 다르다면 해당 상한값으로 변경해야 합니다.)
        
        여기서는 문제의 의도가 "0 이나 음수 거부, 양수여야 하고 상한 미만이어야 함"임을 전제로 합니다.
        상한값은 문제에서 명시되지 않았으므로, 일반적인 상한 (예: 100) 을 사용하거나
        실제 시스템의 상한이 다르다면 이를 수정해야 합니다.
        
        하지만 문제에서 "상한, 상한과 같은 길이, 0 인 길이의 처리는 인쇄 담당자에게 확인할 수 있습니다" 라고 했으므로,
        우리는 상한값을 정의해야 합니다. 여기서는 100cm 를 상한으로 가정합니다.
        만약 상한이 다르다면 100 을 해당 상한값으로 교체하세요.
    """
    # 상한값 정의 (문제에서 명시되지 않았으므로 일반적인 상한 100cm 를 가정) 
    # 실제 시스템의 상한이 다르다면 이 값을 수정해야 합니다.
    MAX_WIDTH = 6
    MAX_HEIGHT = 4
    
    # 음수 또는 0 인 경우 거부
    if width_cm <= 0 or height_cm <= 0:
        return False
    
    # 각 차원이 상한보다 작아야 함 (상한과 같거나 더 크면 거부)
    if width_cm > MAX_WIDTH or height_cm > MAX_HEIGHT:
        return False
    
    # 모든 조건을 만족하면 허용
    return True


if __name__ == "__main__":
    # 간단한 테스트
    # 테스트 케이스: (10, 10) -> True, (100, 10) -> False, (-5, 10) -> False, (0, 10) -> False
    print(fits_print(10, 10))   # True
    print(fits_print(100, 10))  # False (상한과 같음)
    print(fits_print(-5, 10))   # False (음수)
    print(fits_print(0, 10))    # False (0)
    print(fits_print(99, 99))   # True
    print(fits_print(101, 10))  # False (상한 초과)
