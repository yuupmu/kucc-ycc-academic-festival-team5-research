def mask_code(code):
    """
    화면에서 식별코드를 가리는 mask_code 함수입니다.
    
    입력: 영문 대소문자와 숫자로만 된 문자열 (빈 문자열 포함)
    출력: 각 글자를 별표(*) 로 바꾼 문자열
    
    규칙:
    - 입력 문자열의 길이는 출력 문자열의 길이와 동일합니다.
    - 모든 글자는 별표(*) 로 대체됩니다.
    - 원래 대소문자와 순서는 유지되지만, 내용은 가립니다.
    - 공백이나 다른 문자는 입력되지 않습니다.
    """
    return "*" * len(code)