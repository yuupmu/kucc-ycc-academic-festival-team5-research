def clean_title(text):
    """
    표시 제목을 정리하는 함수입니다.
    
    입력: 영문 대소문자, 숫자, 하이픈, ASCII 공백으로만 된 문자열 (빈 문자열 포함)
    출력: 정리된 문자열 (str)
    
    규칙:
    1. 양끝 공백 제거
    2. 영문자는 소문자로 변환
    3. 숫자는 그대로 유지
    4. 내부 공백이 하나인 평범한 단어 사이 공백은 유지
    5. 연속된 내부 공백, 하이픈, 비어 있는 제목은 편집 담당자의 기준을 따름 (현재 구현에서는 유지)
    """
    if not text:
        return ""
    
    # 1. 양끝 공백 제거
    text = text.rstrip()
    
    # 2. 영문자는 소문자로 변환, 숫자는 그대로 유지
    # ASCII 공백과 하이픈도 유지
    text = text.lower()
    
    # 3, 4, 5. 공백과 하이픈 처리
    # 문제 설명에 따르면:
    # - 내부 공백이 하나인 평범한 단어 사이 공백은 유지
    # - 연속된 내부 공백, 하이픈, 비어 있는 제목은 편집 담당자의 기준을 따름
    # 현재 구현은 입력 그대로 (단, 소문자화 및 양끝 공백 제거) 처리합니다.
    # 연속된 공백이나 하이픈을 줄이는 로직은 명시적으로 요구되지 않았으므로 유지합니다.
    
    return text