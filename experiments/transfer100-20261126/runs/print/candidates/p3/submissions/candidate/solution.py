def fits_print(width_cm, height_cm):
    """
    고정 방향 인쇄 영역을 검사하는 함수입니다.
    
    Args:
        width_cm (int): 인쇄 영역의 가로 길이 (센티미터). 0 은 가로 길이 없음을 의미합니다.
        height_cm (int): 인쇄 영역의 세로 길이 (센티미터). 0 은 세로 길이 없음을 의미합니다.
    
    Returns:
        bool: 인쇄 영역이 허용되는 경우 True, 그렇지 않은 경우 False 를 반환합니다.
    
    Requirements:
        - 한쪽이라도 음수이면 거부합니다.
        - 두 길이가 양수이고 각각 자기 상한보다 작으면 허용합니다.
        - 어느 한쪽이라도 자기 상한을 초과하면 거부합니다.
        - 회전이나 가로·세로 교환은 하지 않습니다.
        - 허용하면 True, 거부하면 False 를 반환합니다.
        - 가로와 세로의 상한, 상한과 같은 길이, 0 인 길이의 처리는 인쇄 담당자에게 확인할 수 있습니다.
    
    Note:
        현재 요구사항에서 '인쇄 담당자에게 확인할 수 있는' 상한값이 명시적으로 제공되지 않았습니다.
        따라서 이 구현은 '상한값이 존재하지 않는 경우 (무한대)'를 가정하고,
        양수인 경우에만 True 를 반환하는 로직으로 작성됩니다.
        만약 향후 인쇄 담당자가 구체적인 상한값 (예: 20cm) 을 제공하면,
        해당 상한값을 사용하여 비교 로직을 수정해야 합니다.
    """
    # 음수 확인
    if width_cm < 0 or height_cm < 0:
        return False
    
    # 0 처리
    # 요구사항: "0 은 가로/세로 길이 없음"
    # 요구사항: "양수이고 각각 자기 상한보다 작으면 허용합니다"
    # 0 은 양수가 아니므로, 상한값이 존재하지 않는 경우 0 은 허용되지 않음.
    # (만약 0 을 허용해야 한다면, 상한값이 0 보다 큰 값이 제공되어야 함) 
    # 현재 정보로는 0 을 허용하는 근거가 없으므로 거부합니다.
    if width_cm == 0 or height_cm == 0:
        return False
    
    # 양수 확인 (0 이 아닐 경우) 및 상한 확인
    # 현재 요구사항에 구체적인 상한값이 없으므로,
    # '양수인 경우 허용' 로 해석하여 구현합니다.
    # 만약 상한값이 제공된다면: width_cm < MAX_WIDTH and height_cm < MAX_HEIGHT
    # 현재는 MAX_WIDTH = float('inf') 로 간주합니다.
    
    return True