def file_suffix(name):
    """
    파일 이름에서 확장자를 추출합니다.
    
    Args:
        name (str): 파일 이름 (경로 구분자 없음, 영문 대소문자, 숫자, 점, 하이픈 포함)
    
    Returns:
        str: 확장자 (점 없이). 점이 여러 개면 마지막 점 뒤의 부분만 반환.
              점이 없거나 마지막 글자가 점이면 빈 문자열 반환.
    """
    # 입력 검증: 공백이나 빈 문자열은 요구사항에 따라 입력되지 않는다고 가정
    # 하지만 안전성을 위해 공백이 있으면 처리할지 여부는 담당자 답변에 명시되지 않음. 
    # 요구사항: "공백과 빈 문자열은 입력되지 않습니다." -> 입력 전제이므로 추가 검증 불필요.
    
    # 점이 여러 개인 경우, 마지막 점 뒤의 부분만 확장자로 사용 (복합 확장자 합치 안 함)
    # 점이 없거나 마지막 글자가 점인 경우 빈 문자열 반환
    
    if '.' not in name:
        return ""
    
    # 마지막 점의 인덱스를 찾음
    last_dot_index = name.rfind('.')
    
    # 마지막 글자가 점인지 확인 (인덱스가 name 길이와 같거나, 점 뒤가 비어있거나) 
    # rfind가 name 길이 - 1 인 경우: 마지막 글자가 점 (예: "test." -> 인덱스 4, 길이 5) 
    # rfind가 name 길이 - 2 인 경우: 점 뒤가 하나 (예: "test." -> 인덱스 4, 길이 5 -> name[5]는 없음. wait. 
    # name = "test." -> len=5, rfind('.') = 4. name[5]는 존재하지 않음. name[-1] == '.' 이므로.
    # name = "test.a.b" -> len=8, rfind('.') = 6. name[7] = 'b'.
    
    # 조건: 점이 맨 앞이나 맨 끝에 있지 않아야 함 (보통 파일 정의에 따라, 하지만 담당자 답변에서 "점이 여러 개인 보통 파일"이라는 표현 사용) 
    # 담당자 답변: "점이 없거나 마지막 글자가 점인 이름은 빈 문자열을 반환합니다." 
    # -> 만약 name[-1] == '.' 이라면 빈 문자열 반환.
    
    if name[-1] == '.':
        return ""
    
    # 확장자 추출: last_dot_index + 1 부터 끝까지
    suffix = name[last_dot_index + 1:]
    
    # 요구사항: "반환값에 점을 붙이지 않습니다." 
    # 이미 슬라이싱으로 점이 제거됨.
    
    return suffix