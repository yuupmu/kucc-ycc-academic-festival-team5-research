def clean_title(text: str) -> str:
    # 1. 양끝 공백 제거
    text = text.rstrip()
    
    # 2. 영문자 소문자 변환, 숫자 유지
    text = text.lower()
    
    # 3. 연속된 공백을 하나로 줄임 (하이픈은 유지)
    # 공백과 빈 문자열을 하나로, 하이픈은 그대로
    text = re.sub(r'\s+', ' ', text)
    
    # 4. 하이픈이 연속된 경우를 하나로 줄이지 않는지 확인 필요
    # H2: 하이픈은 개수와 위치를 그대로 유지합니다.
    # 따라서 위에서 \s+ 로 처리할 때 하이픈도 포함시키면 안 됨.
    # 다시 생각: 공백은 줄임, 하이픈은 유지.
    # 연속된 공백 -> 하나
    # 연속된 하이픈 -> 유지 (H2)
    # 공백과 하이픈이 섞여 있을 때?
    # "a  - b" -> "a - b" (공백 하나, 하이픈 하나)
    # "a  -  b" -> "a - b" (공백 줄임, 하이픈 유지)
    # "a - - b" -> "a - - b" (하이픈 유지)
    # "a   b" -> "a b"
    # 정규식: 공백만 줄이고 하이픈은 untouched.
    # \s+ 는 공백, 탭 등. 하이픈은 \s 이 아니므로 \s+ 는 하이픈을 건드리지 않음.
    # 하지만 "a  -" -> "a -" (여러 공백 줄임)
    # "a - -" -> "a - -" (하이픈 유지)
    # "a - - b" -> "a - - b"
    # "a   -" -> "a -"
    # "a -   b" -> "a - b"
    # 이 로직은 H1 (공백 줄임) 과 H2 (하이픈 유지) 를 모두 만족.
    text = re.sub(r'\s+', ' ', text)
    
    # 5. 앞뒤 공백 제거 (rstrip 처리 후 다시 strip 필요? rstrip 만 했음. 정규식 후에도 안전성 위해 strip)
    text = text.strip()
    
    # 6. 빈 문자열이면 'untitled' 반환
    if not text:
        return "untitled"
    
    return text

import re