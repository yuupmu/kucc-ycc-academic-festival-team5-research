import re


def clean_title(text):
    """
    표시 제목을 정리하는 함수입니다.
    
    입력: 영문 대소문자, 숫자, 하이픈, ASCII 공백으로만 된 문자열 (빈 문자열 포함)
    출력: 정리된 문자열
    
    동작:
    1. 양끝 공백 제거
    2. 모든 영문자를 소문자로 변환
    3. 연속된 내부 공백, 하이픈, 빈 제목 (연속된 공백) 을 하나의 공백으로 통일
    4. 단어 사이 공백은 하나 유지
    """
    # 1. 양끝 공백 제거
    text = text.rstrip()
    
    # 2. 모든 영문자를 소문자로 변환
    text = text.lower()
    
    # 3. 연속된 공백, 하이픈, 빈 문자열 (두 공백 사이) 을 하나의 공백으로 통일
    # 정규식: \s+ 는 하나 이상의 공백 (여러 개 연속된 공백) 을 의미
    # - 는 하이픈을 의미
    # [\s-]+ 는 하나 이상의 공백 또는 하이픈을 의미
    # 이를 하나의 공백 ' ' 으로 치환함
    # 빈 문자열 (예: " " * 3) 의 경우, \s+ 가 모든 공백을 하나의 공백으로 줄여 " " 가 됨
    # 하이픈과 공백이 섞여 있을 경우 (예: "a - b  c") 는 "a - b c" 가 됨
    text = re.sub(r'[\s-]+', ' ', text)
    
    # 4. 결과에서 앞뒤 공백 제거 (rstrip 처리는 이미 했지만, 정규식 후에도 안전성을 위해)
    text = text.strip()
    
    return text


