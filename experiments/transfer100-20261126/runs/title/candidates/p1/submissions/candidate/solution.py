import re


def clean_title(text):
    """
    표시 제목을 정리하는 함수입니다.
    
    입력: 영문 대소문자, 숫자, 하이픈, ASCII 공백으로만 된 문자열 (빈 문자열 포함)
    출력: 정리된 문자열
    
    동작:
    1. 양끝 공백 제거
    2. 모든 영문자를 소문자로 변환
    3. 연속된 내부 공백, 하이픈, 빈 제목 (연속된 공백) 을 하나의 공백으로 통일
    4. 단어 사이 공백은 하나 유지
    """
    # 1. 양끝 공백 제거
    text = text.rstrip()
    
    # 2. 모든 영문자를 소문자로 변환
    text = text.lower()
    
    # 3. 연속된 공백, 하이픈, 빈 문자열을 하나의 공백으로 통일
    # 정규식: 공백, 하이픈, 빈 문자열 (\s) 을 하나씩 묶어서 하나의 공백으로 치환
    # \s+ 는 하나 이상의 공백을 의미하므로, 이를 하나의 공백으로 줄여줌
    # 하이픈도 연속된 경우를 하나의 하이픈으로 줄여줌
    # 빈 문자열 (두 공백 사이) 도 하나의 공백으로 치환됨
    text = re.sub(r'[\s-]+', ' ', text)
    
    # 4. 결과에서 앞뒤 공백 제거 (rstrip 처리는 이미 했지만, 정규식 후에도 안전성을 위해)
    text = text.strip()
    
    return text

